/* Regenerates src/lib/image-meta.ts (intrinsic size + tiny blur placeholder) for every public/images/site/*.jpg.
   Usage: node scripts/image-meta.cjs   — run after adding or replacing photos. */
const sharp = require("sharp");
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "public", "images", "site");
(async () => {
  const meta = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".jpg")).sort()) {
    const buf = fs.readFileSync(path.join(dir, file));
    const m = await sharp(buf).metadata();
    const tiny = await sharp(buf).rotate().resize(16).jpeg({ quality: 45 }).toBuffer();
    meta[file.replace(/\.jpg$/, "")] = { w: m.width, h: m.height, blur: "data:image/jpeg;base64," + tiny.toString("base64") };
  }
  const out = "// Generated by scripts/image-meta.cjs – tiny blur placeholders + intrinsic sizes.\nexport const IMAGE_META: Record<string, { w: number; h: number; blur: string }> = " + JSON.stringify(meta, null, 1) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "src", "lib", "image-meta.ts"), out);
  console.log("image-meta:", Object.keys(meta).length, "images");
})();
